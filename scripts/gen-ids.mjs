// Regenerates src/language/ids.generated.ts from the official Mojang ids package: node scripts/gen-ids.mjs
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const vd = require('@minecraft/vanilla-data');
const { version } = JSON.parse(readFileSync(new URL('../node_modules/@minecraft/vanilla-data/package.json', import.meta.url), 'utf8'));
const ids = (o) => [...new Set(Object.values(o).map((v) => String(v).replace(/^minecraft:/, '')))].sort();

const wrap = (items) => {
  const lines = [];
  let line = '  ';
  for (const id of items) {
    const piece = `'${id}', `;
    if (line.length + piece.length > 140) {
      lines.push(line.trimEnd());
      line = '  ';
    }
    line += piece;
  }
  lines.push(line.trimEnd());
  return lines.join('\n');
};

const sections = [
  ['ENTITY_IDS', 'Entity type ids', vd.MinecraftEntityTypes],
  ['BLOCK_IDS', 'Block ids', vd.MinecraftBlockTypes],
  ['ITEM_IDS', 'Item ids', vd.MinecraftItemTypes],
  ['EFFECT_IDS', 'Effect ids', vd.MinecraftEffectTypes],
  ['ENCHANTMENT_IDS', 'Enchantment ids', vd.MinecraftEnchantmentTypes],
];
let out = `// Generated by scripts/gen-ids.mjs from @minecraft/vanilla-data ${version} (MIT, Mojang). Do not edit by hand.\n`;
out += `// The ids are those of Bedrock ${version}; a game version that is older (the NetEase edition often is) may not have all of them.\n\n`;
out += `export const IDS_VERSION = '${version}';\n`;
for (const [name, doc, data] of sections) out += `\n/** ${doc}, without the minecraft: prefix. */\nexport const ${name}: string[] = [\n${wrap(ids(data))}\n];\n`;
writeFileSync(new URL('../src/language/ids.generated.ts', import.meta.url), out);
console.log(`ids ${version}: ${sections.map(([n, , d]) => `${n} ${ids(d).length}`).join(', ')}`);